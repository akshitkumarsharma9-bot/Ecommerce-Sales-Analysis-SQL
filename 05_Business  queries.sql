    TO_CHAR(order_purchase_timestamp, 'YYYY-MM') AS order_month,
    COUNT(order_id) AS total_orders
FROM orders
GROUP BY TO_CHAR(order_purchase_timestamp, 'YYYY-MM')
ORDER BY order_month;

