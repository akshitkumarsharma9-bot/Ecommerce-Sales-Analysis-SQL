-- 21. find total revenue generated by each state 
SELECT c.customer_state,         
       SUM(op.payment_value) AS total_revenue
FROM customers c
JOIN orders o
ON c.customer_id = o.customer_id
join order_payments op
ON o.order_id = op.order_id
GROUP BY customer_state
ORDER BY total_revenue DESC;

-- 22. find the top 10 cities by total revenue
SELECT c.customer_city, 
       SUM(op.payment_value) AS total_revenue
FROM customers c
JOIN orders o
ON c.customer_id = o.customer_id
JOIN order_payments op
ON o.order_id = op.order_id
GROUP BY customer_city
ORDER BY  total_revenue DESC;
	   
-- 23. Find the Top 10 Product Categories by Revenue
SELECT
    pct.product_category_name_english,
    SUM(op.payment_value) AS total_revenue
FROM products p
JOIN product_category_name_translation pct
    ON p.product_category_name = pct.product_category_name
JOIN order_items oi
    ON p.product_id = oi.product_id
JOIN order_payments op
    ON oi.order_id = op.order_id
GROUP BY pct.product_category_name_english
ORDER BY total_revenue DESC
LIMIT 10;

-- 24. Find the Top 10 best selling product categories
SELECT
     pct.product_category_name_english,
    COUNT(oi.product_id) AS total_product_sold
FROM order_items oi
JOIN products p
    ON oi.product_id = p.product_id
JOIN product_category_name_translation pct
    ON p.product_category_name = pct.product_category_name
GROUP BY pct.product_category_name_english
ORDER BY total_product_sold DESC
LIMIT 10;

-- 25. find the average delivery time (in days)
SELECT 
ROUND(AVG(order_delivered_customer_date::DATE - order_purchase_timestamp::DATE),2)
FROM orders
WHERE order_delivered_customer_date IS NOT NULL;

-- 26. find the top 10 fatest delivered order
SELECT order_id,
       (order_delivered_customer_date::DATE - order_purchase_timestamp::DATE) AS delivery_days
FROM orders
WHERE order_delivered_customer_date IS NOT NULL
ORDER BY delivery_days ASC
LIMIT 10;

-- 27. Find the Top 10 States by Total Revenue
SELECT
    c.customer_state,
