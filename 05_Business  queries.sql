-- 1. How many total customer are there?
SELECT COUNT(*) AS total_customers
FROM customers;

-- 2. how many total order are there?
SELECT COUNT(*) AS total_orders
FROM orders;

-- 3. how many orders have been placed for each order status?
SELECT order_status,count(*) AS total_orders_placed
FROM orders
GROUP BY order_status
ORDER BY total_orders_placed DESC;

-- 4. how many unique customers have placed order?
SELECT COUNT(DISTINCT customer_id)AS unique_customers FROM orders;

-- 5. find the top 10 city with the highest number of customers?
SELECT customer_city,
       COUNT(*) AS total_customers
FROM customers
GROUP BY customer_city
ORDER BY total_customers
limit 10;

-- 6. find the top 10 customers who placed the most orders
