-- 31. Find the Top 10 Sellers by Total Revenue
SELECT
    s.seller_id,
    s.seller_city,
    SUM(op.payment_value) AS total_revenue
FROM sellers s
JOIN order_items oi
    ON s.seller_id = oi.seller_id
